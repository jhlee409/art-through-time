const fs = require('fs');
const file = 'data/미술사조/d3a0d1b58bda4f1f1ed342df-1.html';
let html = fs.readFileSync(file, 'utf8');
const link = (id, original, korean, display) => `<a class="art-atlas-artist-link" href="../../index.html?artist=${id}" target="_blank" rel="noopener" data-artist-id="${id}" data-uh-original="${original}" data-uh-korean="${korean}" data-uh-display-korean="${display}" title="${korean} 연표로 이동">${display}</a>`;
const eyck = link('artist-Q102272','Jan van Eyck','반 에이크, 얀','얀 반 에이크');
const weyden = link('artist-Q68631','Rogier van der Weyden','반 데르 베이던, 로히어르','로히어르 반 데르 베이던');
const bruegel = link('artist-Q43270','Pieter Brueghel the Elder','대 피터르 브뤼헐','브뤼헐');
const durer = link('artist-Q5580','Albrecht Dürer','뒤러, 알브레히트','알브레히트 뒤러');
const cranach = link('artist-Q191748','Lucas Cranach the Elder','크라나흐, 루카스','루카스 크라나흐');
const holbein = link('artist-Q48319','Hans Holbein the Younger','홀바인, 한스','한스 홀바인 2세');
const altdorfer = link('artist-Q153746','Albrecht Altdorfer','알브레히트 알트도르퍼','알브레히트 알트도르퍼');
const huber = link('artist-Q610556','Wolf Huber','볼프 후버','볼프 후버');
const replacement = `      <tr><td>저지대 — 초기 네덜란드 회화, 15세기</td><td>유화의 투명한 색층, 반사광, 사물의 재질과 일상 공간을 세밀하게 관찰하는 방식이 두드러졌다. ${eyck}의 물질 묘사와 ${weyden}의 압축된 감정이 이 흐름의 핵심이다.</td><td>${eyck}, ${weyden}</td></tr>
      <tr><td>플랑드르 — 16세기 르네상스</td><td>농민의 삶과 광대한 풍경을 도덕적·서사적 상상력과 결합해, 초기 네덜란드 회화 이후의 저지대 전통을 새롭게 확장했다.</td><td>${bruegel}</td></tr>
      <tr><td>독일어권 — 독일 르네상스</td><td>종교개혁과 궁정 후원 속에서 판화, 초상, 책 삽화가 이탈리아의 비례·원근법 연구와 결합했다.</td><td>${durer}, ${cranach}, ${holbein}</td></tr>
      <tr><td>독일·오스트리아 — 도나우파</td><td>도나우강 유역의 숲·산·빛을 강한 선과 대기 속에 담아, 풍경을 종교·역사 서사의 배경에서 독자적 주제로 끌어올렸다.</td><td>${altdorfer}, ${huber}</td></tr>`;
const tableRows = /<tr>\s*<td>네덜란드·플랑드르<\/td>[\s\S]*?<\/tr>\s*<tr>\s*<td>북유럽 르네상스<\/td>[\s\S]*?<\/tr>\s*<tr>\s*<td>독일 르네상스<\/td>[\s\S]*?<\/tr>\s*<tr>\s*<td>도나우파 — 남독일·오스트리아<\/td>[\s\S]*?<\/tr>/;
if (tableRows.test(html)) html = html.replace(tableRows, replacement);
else if (!html.includes('<td>저지대 — 초기 네덜란드 회화, 15세기</td>')) throw new Error('기존 저지대·독일어권 표 행을 찾지 못했습니다.');
const heading = '<h3>여러 국가에서의 전개 — 대표 화가의 대표작</h3>';
const sectionStart = html.indexOf(heading);
const gridStart = html.indexOf('<div class="movement-work-grid three">', sectionStart);
const sectionEnd = html.indexOf('</section>', gridStart);
const gridEnd = html.lastIndexOf('</div>', sectionEnd);
if (sectionStart < 0 || gridStart < 0 || sectionEnd < 0 || gridEnd < 0) throw new Error('르네상스 대표작 카드 그리드를 찾지 못했습니다.');
const grid = html.slice(gridStart, gridEnd + '</div>'.length);
const cards = grid.match(/<article class="movement-work-card">[\s\S]*?<\/article>/g) || [];
const ids = ['artist-Q5580','artist-Q191748','artist-Q48319'];
const targets = Object.fromEntries(ids.map(id => [id, cards.filter(card => card.includes(`data-artist-id="${id}"`))]));
if (ids.some(id => !targets[id].length)) throw new Error(`독일 르네상스 카드를 찾지 못했습니다: ${ids.filter(id => !targets[id].length).join(', ')}`);
const firstTargetIndex = cards.findIndex(card => ids.some(id => card.includes(`data-artist-id="${id}"`)));
const reordered = cards.filter(card => !ids.some(id => card.includes(`data-artist-id="${id}"`)));
reordered.splice(firstTargetIndex, 0, ...ids.map(id => targets[id][0]));
const firstCardStart = grid.indexOf(cards[0]);
const lastCard = cards[cards.length - 1];
const lastCardEnd = grid.lastIndexOf(lastCard) + lastCard.length;
if (firstCardStart < 0 || lastCardEnd < 0) throw new Error('대표작 카드 영역을 재구성하지 못했습니다.');
const newGrid = grid.slice(0, firstCardStart) + reordered.join('\n') + grid.slice(lastCardEnd);
html = html.slice(0, gridStart) + newGrid + html.slice(gridEnd + '</div>'.length);
fs.writeFileSync(file, html);
console.log('Restructured Renaissance country table and ordered German representative cards by activity period.');
